package mx.com.mundodafne.ms.catalogos.gmj.paciente.dto;

public class GmjPacienteAntPatologicosDTO {
	private String desconoce;
	private String enfermedad;
	private String tipoEnfermedad;
	private String tiempoEvolucion;
	private String tratamiento;
	/**
	 * @return the desconoce
	 */
	public String getDesconoce() {
		return desconoce;
	}
	/**
	 * @param desconoce the desconoce to set
	 */
	public void setDesconoce(String desconoce) {
		this.desconoce = desconoce;
	}
	/**
	 * @return the enfermedad
	 */
	public String getEnfermedad() {
		return enfermedad;
	}
	/**
	 * @param enfermedad the enfermedad to set
	 */
	public void setEnfermedad(String enfermedad) {
		this.enfermedad = enfermedad;
	}
	/**
	 * @return the tipoEnfermedad
	 */
	public String getTipoEnfermedad() {
		return tipoEnfermedad;
	}
	/**
	 * @param tipoEnfermedad the tipoEnfermedad to set
	 */
	public void setTipoEnfermedad(String tipoEnfermedad) {
		this.tipoEnfermedad = tipoEnfermedad;
	}
	/**
	 * @return the tiempoEvolucion
	 */
	public String getTiempoEvolucion() {
		return tiempoEvolucion;
	}
	/**
	 * @param tiempoEvolucion the tiempoEvolucion to set
	 */
	public void setTiempoEvolucion(String tiempoEvolucion) {
		this.tiempoEvolucion = tiempoEvolucion;
	}
	/**
	 * @return the tratamiento
	 */
	public String getTratamiento() {
		return tratamiento;
	}
	/**
	 * @param tratamiento the tratamiento to set
	 */
	public void setTratamiento(String tratamiento) {
		this.tratamiento = tratamiento;
	}
	
	
}
