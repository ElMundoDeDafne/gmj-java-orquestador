package mx.com.mundodafne.ms.catalogos.gmj.entity;

public class CatOcupacion {
	
	private Long idOcupacion;
	private String clave;
	private String descOcupacion;
	/**
	 * @return the idOcupacion
	 */
	public Long getIdOcupacion() {
		return idOcupacion;
	}
	/**
	 * @param idOcupacion the idOcupacion to set
	 */
	public void setIdOcupacion(Long idOcupacion) {
		this.idOcupacion = idOcupacion;
	}
	/**
	 * @return the clave
	 */
	public String getClave() {
		return clave;
	}
	/**
	 * @param clave the clave to set
	 */
	public void setClave(String clave) {
		this.clave = clave;
	}
	/**
	 * @return the descOcupacion
	 */
	public String getDescOcupacion() {
		return descOcupacion;
	}
	/**
	 * @param descOcupacion the descOcupacion to set
	 */
	public void setDescOcupacion(String descOcupacion) {
		this.descOcupacion = descOcupacion;
	}
	
	
}
